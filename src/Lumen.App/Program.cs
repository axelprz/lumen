using Velopack;

namespace Lumen.App;

/// <summary>The entry point. Velopack's install, update and uninstall hooks run first and exit; a normal start goes on.</summary>
public static class Program
{
    [STAThread]
    public static void Main()
    {
        VelopackApp.Build().Run();

        var app = new App();
        app.InitializeComponent();
        app.Run();
    }
}
